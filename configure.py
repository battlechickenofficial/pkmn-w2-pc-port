#!/usr/bin/env python3
"""Generate build.ninja: delink -> link with mwldarm -> build the ROM with dsd -> check its SHA-1.

Usage: python configure.py [version]      (default w2), then: tools/bin/ninja.exe

The dsd config in config/<version>/ comes from `dsd init` plus tools/dsd/apply_fixups.py; see tools/dsd/README.md.
"""
import json, subprocess, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
VERSIONS = {
    # B2 is missing: its baserom's DSi area is a DS-mode read (docs/ROADMAP.md, dump issues), so dsd can't extract it.
    'w2': {'baserom': 'baserom/baserom_w2.nds', 'rom': 'pokewhite2_jp.nds',
           'sha1': '01666f87838c57dc0a65930a916982ad8941d8fb'},
}

EXE = '.exe' if sys.platform == 'win32' else ''
# Native separators: Windows' CreateProcess won't run a relative program path written with forward slashes
DSD = str(Path(f'tools/bin/dsd{EXE}'))
MWLD_VERSION = 'dsi/1.1'
MWLD = str(Path(f'tools/mwccarm/{MWLD_VERSION}/mwldarm.exe'))
WINE = '' if sys.platform == 'win32' else 'wibo '
PYTHON = sys.executable

LD_FLAGS = ' '.join([
    '-proc arm946e',
    '-nodead',              # keep every delinked object, dead-stripping would drop unreferenced ones
    '-nostdlib',
    '-interworking',
    '-map closure,unused',
    '-msgstyle gcc',
    '-m Entry',             # the ARM9 entry point, named by dsd init
])


def config_files(config_dir):
    return sorted(str(p.relative_to(ROOT)) for name in ('delinks.txt', 'relocs.txt', 'symbols.txt', 'config.yaml')
                  for p in config_dir.rglob(name))


def main(version):
    v = VERSIONS[version]
    config_dir = ROOT / 'config' / version
    arm9_config = f'config/{version}/arm9/config.yaml'
    extract_config = f'extract/{version}/config.yaml'
    build = f'build/{version}'
    if not (ROOT / extract_config).exists():
        sys.exit(f'{extract_config} is missing; run: {DSD} rom extract --rom {v["baserom"]} --output-path extract/{version}')

    delinks = json.loads(subprocess.run([str(ROOT / DSD), 'json', 'delinks', '--config-path', arm9_config],
                                        cwd=ROOT, capture_output=True, text=True, check=True).stdout)
    objects = [f['delink_file'].replace('\\', '/') for f in delinks['files']]
    lcf = delinks['arm9_lcf_file'].replace('\\', '/')
    objects_txt = delinks['arm9_objects_file'].replace('\\', '/')
    configs = config_files(config_dir)

    out = []
    w = out.append
    w('# Generated by configure.py; do not edit.\n')
    w(f'rule delink\n  command = {DSD} delink --config-path $config\n  description = Delinking {version}\n')
    w(f'rule lcf\n  command = {DSD} lcf --config-path $config\n  description = Generating linker script\n')
    w(f'rule mwld\n  command = {WINE}{MWLD} {LD_FLAGS} @$objects $lcf -o $out\n  description = Linking $out\n')
    w(f'rule rom_config\n  command = {DSD} rom config --elf $in --config $config\n  description = Configuring ROM\n')
    w(f'rule rom_build\n  command = {DSD} rom build --config $in --rom $out\n  description = Building $out\n')
    w(f'rule check_modules\n  command = {PYTHON} tools/stamp.py $out {DSD} check modules --config-path $config --fail\n'
      '  description = Checking modules\n')
    w(f'rule sha1\n  command = {PYTHON} tools/stamp.py $out --sha1 $sha1 $in\n  description = Checking $in\n')
    w(f'rule configure\n  command = {PYTHON} configure.py {version}\n  generator = 1\n  description = Regenerating build.ninja\n')

    w(f'build {" ".join(objects)}: delink | {" ".join(configs)}\n  config = {arm9_config}\n')
    w(f'build {lcf} {objects_txt}: lcf | {" ".join(configs)}\n  config = {arm9_config}\n')
    w(f'build {build}/arm9.o: mwld {" ".join(objects)} | {lcf} {objects_txt} {MWLD}\n'
      f'  objects = {objects_txt}\n  lcf = {lcf}\n')
    w(f'build {build}/build/rom_config.yaml: rom_config {build}/arm9.o\n  config = {arm9_config}\n')
    w(f'build {build}/{v["rom"]}: rom_build {build}/build/rom_config.yaml | {extract_config}\n')
    w(f'build {build}/modules.ok: check_modules {build}/build/rom_config.yaml\n  config = {arm9_config}\n')
    w(f'build {build}/rom.ok: sha1 {build}/{v["rom"]}\n  sha1 = {v["sha1"]}\n')
    w(f'build {version}: phony {build}/modules.ok {build}/rom.ok\n')
    w(f'build build.ninja: configure | configure.py {" ".join(configs)}\n')
    w(f'default {version}\n')
    (ROOT / 'build.ninja').write_text('\n'.join(out))
    print(f'Wrote build.ninja for {version}: {len(objects)} objects')


if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else 'w2')
